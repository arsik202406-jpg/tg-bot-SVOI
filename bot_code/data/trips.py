def get_free_seats(trip_id: str) -> int:
    return TRIPS_SEATS.get(trip_id, 5)

def set_free_seats(trip_id: str, count: int) -> int:
    val = max(0, min(8, count))
    TRIPS_SEATS[trip_id] = val
    return val

def get_trip_date(trip_id: str) -> str:
    trip = TRIPS_CATALOG.get(trip_id, {})
    return trip.get("date", "Найближчі вихідні")

def set_trip_date(trip_id: str, new_date: str) -> str:
    if trip_id in TRIPS_CATALOG:
        TRIPS_CATALOG[trip_id]["date"] = new_date.strip()
    return new_date.strip()

