def format_trip_card_html(trip_id: str, is_admin: bool = False) -> str:
    """
    Формує єдину структуровану картку туру за сіткою:
    - Заголовок жирним: Прапор + Назва | Дата
    - Коротка програма по годинах або локації (3-4 буліти)
    - Блок цитати <blockquote> та <code>
    - Чіткий блок унизу: 💶 Ціна: XX€ | 🔥 Місць: X з 8
    """
    trip = TRIPS_CATALOG.get(trip_id)
    if not trip:
        return "Тур не знайдено"

    flag = trip.get("flag", "🇪🇺")
    title = trip.get("short_title", trip.get("title", ""))
    date_str = get_trip_date(trip_id)
    price = trip.get("price", 120)
    duration = trip.get("duration", "1 день")
    free_seats = get_free_seats(trip_id)
    highlights = trip.get("highlights", [])

    bullets = "\n".join([f"• {item}" for item in highlights[:4]])
    payment_rule = (
        "<code>0% передоплати</code> (оплата при посадці в день виїзду)"
        if duration == "1 день"
        else "Готель включено (фіксація броні готелю)"
    )

    text = (
        f"{flag} <b>{title} | {date_str}</b>\n"
        f"⏱ <i>Тривалість: {duration} • Комфортний Opel Vivaro (8 місць)</i>\n\n"
        f"📍 <b>Програма та головні локації:</b>\n"
        f"{bullets}\n\n"
        f"<blockquote>💡 <b>Умови:</b> {payment_rule}\n"
        f"🏡 <b>Логістика:</b> Збір за адресою (Door-to-Door) по Саарланду, Тріру та Люксембургу.</blockquote>\n\n"
        f"💶 <b>Ціна: {price}€</b>  |  🔥 <b>Місць: {free_seats} з 8</b>"
    )

    if is_admin:
        text += (
            "\n\n👑 <i>Панель адміна: ви можете змінити кількість місць, дату виїзду або постер (фото) кнопками нижче.</i>"
        )
    return text

